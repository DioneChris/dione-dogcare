"""Export the Dione logo SVG as absolute cubic segments for the walking rig (logo2_data.js)."""
import re, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from svgpath import parse

src = open(os.path.join(HERE, 'dione-logo.svg'), encoding='utf-8').read()
paths = re.findall(r'<path class="(cls-\d)" d="([^"]+)"', src)
col = dict(re.findall(r'\.(cls-\d)\s*\{\s*fill:\s*(#[0-9a-fA-F]+)', src))
P = [(c, d, parse(d)) for c, d in paths]
r = lambda v: round(v, 3)
segs = lambda subs: [[[r(c) for p in sg for c in p] for sg in sp] for sp in subs]

# indices in the file: 0-23 wordmark glyph pairs, 24 arch, 25/28 nose marks, 26 far fore leg, 27 far hind leg, 29 dog
glyphs = ['D', 'i', 'o', 'n', 'e', 'D', 'o', 'g', 'C', 'a', 'r', 'e']
word = []
for g in range(12):
    word.append({'glyph': glyphs[g], 'line': 0 if g < 5 else 1, 'd': [P[2 * g][1], P[2 * g + 1][1]]})
data = {
    'colors': {'cream': col['cls-1'], 'olive': col['cls-2']},
    'viewBox': [0, 0, 841.89, 595.28],
    'arch': P[24][1],
    'dog': segs(P[29][2]),
    'nose': [segs(P[25][2]), segs(P[28][2])],
    'farFore': segs(P[26][2]),
    'farHind': segs(P[27][2]),
    'farForeD': P[26][1], 'farHindD': P[27][1], 'dogD': P[29][1], 'noseD': [P[25][1], P[28][1]],
    'word': word,
}
out = os.path.join(HERE, 'logo2_data.js')
open(out, 'w').write('// generated by export_data.py from dione-logo.svg\nvar LOGO2 = ' + json.dumps(data, separators=(',', ':')) + ';\nif (typeof module !== "undefined") module.exports = LOGO2;\n')
print('wrote', out, os.path.getsize(out), 'bytes; dog segs', [len(s) for s in P[29][2]])
